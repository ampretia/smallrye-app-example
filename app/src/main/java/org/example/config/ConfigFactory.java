package org.example.config;

import io.smallrye.config.EnvConfigSource;
import io.smallrye.config.PropertiesConfigSource;
import io.smallrye.config.SmallRyeConfig;
import io.smallrye.config.SmallRyeConfigBuilder;
import io.smallrye.config.source.yaml.YamlConfigSource;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.net.URL;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Properties;
import org.eclipse.microprofile.config.spi.ConfigSource;

/**
 * Builds a {@link SmallRyeConfig} by hand, with no CDI container or application server.
 *
 * <p>Sources, highest priority first. A key in a higher source hides the same key in every lower
 * one; keys are resolved individually, so sources merge rather than replace each other.
 *
 * <pre>
 *   500  command line         --app.port=9000          CommandLineConfigSource
 *   400  system properties    -Dapp.port=9000          PropertiesConfigSource
 *   300  environment          APP_PORT=9000            EnvConfigSource
 *   275  external file        --app.config-file=x.yaml YamlConfigSource / PropertiesConfigSource
 *   250  classpath file       application.yaml         YamlConfigSource
 *   min  @WithDefault         in AppConfig             (generated by the mapping)
 * </pre>
 *
 * <p>The environment, system properties and arguments are passed in rather than read globally so
 * tests can build a config for any scenario without mutating process state.
 */
public final class ConfigFactory {

  /** Property naming an external YAML or .properties file. Env var form: APP_CONFIG_FILE. */
  public static final String CONFIG_FILE_KEY = "app.config-file";

  /** Ordinal for the external file: above the packaged file, below the environment. */
  public static final int EXTERNAL_FILE_ORDINAL = 275;

  /** Ordinal for the packaged classpath file. */
  public static final int CLASSPATH_FILE_ORDINAL = 250;

  private static final String CLASSPATH_FILE = "application.yaml";

  private ConfigFactory() {}

  /**
   * Build config from the real process environment.
   *
   * @param args {@code main} arguments
   * @return a fully validated config
   */
  public static SmallRyeConfig create(final String... args) {
    return create(args, System.getenv(), toMap(System.getProperties()));
  }

  /**
   * Build config from explicit inputs.
   *
   * @param args command-line arguments
   * @param env environment variables
   * @param sysProps system properties
   * @return a fully validated config
   * @throws io.smallrye.config.ConfigValidationException if the {@link AppConfig} mapping cannot
   *     be satisfied (missing required value, bad conversion, unknown {@code app.*} key)
   */
  public static SmallRyeConfig create(
      final String[] args, final Map<String, String> env, final Map<String, String> sysProps) {

    final List<ConfigSource> sources = new ArrayList<>();
    sources.add(new CommandLineConfigSource(args));
    sources.add(new PropertiesConfigSource(sysProps, "SysPropConfigSource", 400));
    sources.add(new EnvConfigSource(env, 300));

    // The location of the external file is itself configuration, so resolve it from the
    // sources above (CLI > -D > env) with a small bootstrap config before building the real one.
    final SmallRyeConfig bootstrap = new SmallRyeConfigBuilder().withSources(sources).build();
    bootstrap
        .getOptionalValue(CONFIG_FILE_KEY, String.class)
        .map(Path::of)
        .map(ConfigFactory::loadFile)
        .ifPresent(sources::add);

    classpathFile().ifPresent(sources::add);

    return new SmallRyeConfigBuilder()
        // Enables ${expressions}, %profile.keys, relocations and fallbacks.
        .addDefaultInterceptors()
        .withSources(sources)
        .withConverter(HostPort.class, 100, new HostPortConverter())
        .withMapping(AppConfig.class)
        .build();
  }

  private static ConfigSource loadFile(final Path path) {
    if (!Files.isRegularFile(path)) {
      throw new IllegalArgumentException(CONFIG_FILE_KEY + " does not exist: " + path);
    }
    try {
      final URL url = path.toUri().toURL();
      final String name = path.getFileName().toString().toLowerCase(Locale.ROOT);
      if (name.endsWith(".yaml") || name.endsWith(".yml")) {
        return new YamlConfigSource(url, EXTERNAL_FILE_ORDINAL);
      }
      return new PropertiesConfigSource(url, EXTERNAL_FILE_ORDINAL);
    } catch (IOException e) {
      throw new UncheckedIOException("Cannot read " + path, e);
    }
  }

  private static Optional<ConfigSource> classpathFile() {
    final URL url = ConfigFactory.class.getClassLoader().getResource(CLASSPATH_FILE);
    if (url == null) {
      return Optional.empty();
    }
    try {
      return Optional.of(new YamlConfigSource(url, CLASSPATH_FILE_ORDINAL));
    } catch (IOException e) {
      throw new UncheckedIOException("Cannot read classpath " + CLASSPATH_FILE, e);
    }
  }

  private static Map<String, String> toMap(final Properties props) {
    final Map<String, String> map = new HashMap<>();
    props.stringPropertyNames().forEach(k -> map.put(k, props.getProperty(k)));
    return map;
  }
}
